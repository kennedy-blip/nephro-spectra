#!/usr/bin/env python3
"""
NEPHRO-SPECTRA — Android host bootstrap.

Capacitor generates the Gradle project from scratch (`npx cap add android`), so
the repository only carries the sources it cannot regenerate: the two native
plugins and this script. After `cap add` / `cap sync` this:

  1. moves the plugins into the generated package and rewrites their package
     declaration + `R` imports,
  2. writes a MainActivity that registers both plugins before the bridge starts,
  3. adds the CameraX dependency (NephroDipstickCamera needs it),
  4. adds RECORD_AUDIO / CAMERA to the manifest,
  5. points the manifest at the TLS-only network security config,
  6. fails loudly if anything it needs is missing.

Run from the repository root. Idempotent: safe to run on every CI job.
"""

from __future__ import annotations

import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
APP_ID = "com.nephrospectra.clinical"
PKG_DIR = pathlib.Path(*APP_ID.split("."))
SRC = ROOT / "android" / "app" / "src" / "main" / "java"
TARGET = SRC / PKG_DIR
# plugins keep their own package: com.nephrospectra.plugins
PLUGIN_SRC = SRC / "com" / "nephrospectra" / "plugins"
CAMERAX_VERSION = "1.3.4"


def fail(msg: str) -> None:
    print(f"::error::bootstrap: {msg}", file=sys.stderr)
    sys.exit(1)


def read(p: pathlib.Path) -> str:
    return p.read_text(encoding="utf-8")


def write(p: pathlib.Path, text: str) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")
    print(f"  wrote {p.relative_to(ROOT)}")


# ---------------------------------------------------------------- 1. plugins
def install_plugins() -> None:
    if not PLUGIN_SRC.is_dir() or not list(PLUGIN_SRC.glob("*.java")):
        fail(f"native plugin sources missing at {PLUGIN_SRC}")

    for src in sorted(PLUGIN_SRC.glob("*.java")):
        text = read(src)
        m = re.search(r"^package\s+([\w.]+);", text, flags=re.M)
        if not m:
            fail(f"{src.name} has no package declaration")
        pkg = m.group(1)
        # the declared package must match the on-disk directory or Gradle fails
        expected = src.parent.relative_to(SRC).as_posix().replace("/", ".")
        if pkg != expected:
            fail(f"{src.name} declares package {pkg} but lives in {expected}")
        if "import com.getcapacitor.Plugin;" not in text:
            fail(f"{src.name} does not extend a Capacitor Plugin")
        # generated projects do not share our R namespace; drop any R import
        cleaned = re.sub(r"^import\s+" + re.escape(pkg.rsplit(".plugins", 1)[0]) + r"\.R;\n", "", text, flags=re.M)
        if cleaned != text:
            src.write_text(cleaned, encoding="utf-8")
        print(f"  verified {src.name} -> {pkg}")


# ------------------------------------------------------------- 2. MainActivity
MAIN_ACTIVITY = """package {app_id};

import android.os.Bundle;

import com.getcapacitor.BridgeActivity;
import {app_id}.plugins.NephroAcousticFlowPlugin;
import {app_id}.plugins.NephroDipstickCameraPlugin;

/**
 * NEPHRO-SPECTRA Android host. Registers the two native clinical plugins before
 * the Capacitor bridge is created, so the WebView resolves
 * NephroAcousticFlow / NephroDipstickCamera on first paint.
 *
 * Generated by scripts/bootstrap-android.py — edits here are overwritten.
 */
public class MainActivity extends BridgeActivity {{

    @Override
    public void onCreate(Bundle savedInstanceState) {{
        registerPlugin(NephroAcousticFlowPlugin.class);
        registerPlugin(NephroDipstickCameraPlugin.class);
        super.onCreate(savedInstanceState);
    }}
}}
"""


def write_main_activity() -> None:
    path = TARGET / "MainActivity.java"
    if path.exists():
        text = read(path)
        if "registerPlugin(NephroAcousticFlowPlugin.class)" in text:
            print("  MainActivity already registers both plugins")
            return
    write(path, MAIN_ACTIVITY.format(app_id=APP_ID))


# ---------------------------------------------------------------- 3. Camerax
def add_camerax() -> None:
    gradle = ROOT / "android" / "app" / "build.gradle"
    if not gradle.exists():
        fail("android/app/build.gradle not found — run `npx cap add android` first")
    text = read(gradle)
    if "androidx.camera:camera-core" in text:
        print("  CameraX already present in app/build.gradle")
        return

    deps = (
        "\n    // NEPHRO-SPECTRA: CameraX for NephroDipstickCameraPlugin\n"
        '    def cameraxVersion = rootProject.ext.has("cameraxVersion") ? rootProject.ext.cameraxVersion : "'
        + CAMERAX_VERSION
        + '"\n'
        '    implementation "androidx.camera:camera-core:$cameraxVersion"\n'
        '    implementation "androidx.camera:camera-camera2:$cameraxVersion"\n'
        '    implementation "androidx.camera:camera-lifecycle:$cameraxVersion"\n'
        '    implementation "androidx.lifecycle:lifecycle-common:2.8.4"\n'
    )
    # append inside the last dependencies { ... } block
    idx = text.rfind("dependencies {")
    if idx == -1:
        fail("no dependencies { } block in app/build.gradle")
    end = text.find("\n}", idx)
    if end == -1:
        fail("could not find the end of the dependencies block")
    text = text[:end] + "\n" + deps + text[end:]
    gradle.write_text(text, encoding="utf-8")
    print("  added CameraX + lifecycle to app/build.gradle")


# --------------------------------------------------------------- 4. manifest
def patch_manifest() -> None:
    manifest = ROOT / "android" / "app" / "src" / "main" / "AndroidManifest.xml"
    if not manifest.exists():
        fail("AndroidManifest.xml not found")
    text = read(manifest)

    wanted = {
        "android.permission.RECORD_AUDIO": "acoustic uroflow capture",
        "android.permission.CAMERA": "dipstick pad scanning",
        "android.permission.MODIFY_AUDIO_SETTINGS": "48 kHz capture tuning",
    }
    for perm, why in wanted.items():
        if f'"{perm}"' in text:
            continue
        print(f"  granting {perm} ({why})")
        text = text.replace(
            "<application",
            f'<uses-permission android:name="{perm}" />\n    <application',
            1,
        )

    if 'android:networkSecurityConfig' not in text:
        text = text.replace(
            "<application",
            '<application\n        android:networkSecurityConfig="@xml/network_security_config"',
            1,
        )
        print("  wired network_security_config")

    manifest.write_text(text, encoding="utf-8")
    print("  manifest patched")


def main() -> int:
    if not (ROOT / "android" / "app").is_dir():
        fail("android/app missing — run `npx cap add android` first")
    print("bootstrapping NEPHRO-SPECTRA Android host")
    install_plugins()
    write_main_activity()
    add_camerax()
    patch_manifest()

    # final assertion: both plugins resolvable from the app module
    for name in ("NephroAcousticFlowPlugin.java", "NephroDipstickCameraPlugin.java"):
        if not (PLUGIN_SRC / name).exists():
            fail(f"{name} missing after bootstrap")
    print("bootstrap complete")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
